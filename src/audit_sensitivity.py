"""Sensitivity analyses behind the 2026-10 publication audit.

Four checks, each tied to a specific sentence in the article:

1. Fig D robustness — Pearson r between confidential share and homicide-victim rate,
   with leave-one-out range, Spearman rho and a record-weighted r. Supports the
   wording "weakly negative ... the robust finding is the absence of any positive
   relationship".
2. Fig I/J — correlation of the national series in levels and in first differences,
   and the substitution sums (homicides + found dead vs homicides + still missing).
3. Fields that survive redaction — what a CONFIDENCIAL row actually carries.
4. Confidentiality by filing authority (ORIGEN_REPORTE) within states — article §6
   and fig K (adopted from editorial proposal E-3).

Needs the gitignored record-level mirror; reads it read-only. Everything else comes
from the hash-verified freeze. Writes reports/audit/sensitivity_results.md.

    python src/audit_sensitivity.py [path/to/rnpdno_mirror_2025-12-02.csv]
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import pearsonr, spearmanr

ROOT = Path(__file__).resolve().parents[1]
FREEZE = ROOT / "data" / "publication_freezes" / "2026-08-15"
D = FREEZE / "derived"
MIRROR = Path(sys.argv[1]) if len(sys.argv) > 1 else FREEZE / "sources" / "rnpdno_mirror_2025-12-02.csv"
OUT = ROOT / "reports" / "audit" / "sensitivity_results.md"


def wcorr(a, b, w):
    a = a - np.average(a, weights=w)
    b = b - np.average(b, weights=w)
    return float(np.sum(w * a * b) / np.sqrt(np.sum(w * a * a) * np.sum(w * b * b)))


def main() -> None:
    lines = ["# Sensitivity results — publication audit 2026-10-12", "",
             "Generated by `src/audit_sensitivity.py`. Freeze 2026-08-15; record-level "
             "mirror 2025-12-02.", ""]

    # 1. Fig D
    e = pd.read_csv(D / "state_opacity_enriched.csv")
    lines += ["## 1. Fig D: confidential share vs homicide-victim rate (32 states)", "",
              "| variable | n | Pearson r (p) | Spearman rho (p) | leave-one-out r range |",
              "|---|---:|---:|---:|---|"]
    for v in ["homicide_victims_2015_2025_per100k", "kidnapping_victims_2015_2025_per100k",
              "femicide_victims_2015_2025_per100k", "pibe_per_capita_2024_2018_mxn",
              "corruption_prevalence_2025_per100k", "resolution_share"]:
        x, y = e[v], e["confidential_share"]
        pr, sr = pearsonr(x, y), spearmanr(x, y)
        loo = [pearsonr(x.drop(i), y.drop(i))[0] for i in x.index]
        lines.append(f"| {v} | {len(x)} | {pr[0]:.3f} ({pr[1]:.3f}) | {sr[0]:.3f} ({sr[1]:.3f}) "
                     f"| {min(loo):.3f} to {max(loo):.3f} |")
    k = e.entidad != "COLIMA"
    x = e["homicide_victims_2015_2025_per100k"]
    lines += ["", f"- Without Colima: r = {pearsonr(x[k], e.confidential_share[k])[0]:.3f}",
              f"- Weighted by unresolved records: r = {wcorr(x, e.confidential_share, e.total_records):.3f}",
              "- Reading: no specification yields a positive association; the size of the "
              "negative one depends on Colima.", ""]

    # 2. national series
    h = pd.read_csv(D / "incidence_vs_homicide.csv").set_index("year")
    fy = pd.read_csv(D / "flow_by_year.csv", index_col=0)
    fy.index = [str(i).strip() for i in fy.index]
    a = h.loc[2015:2024]
    hom, dis = a.homicide_victims_annualised.values, a.disappearances_recorded.values
    lines += ["## 2. Fig I/J: national series", "",
              f"- Pearson r levels 2015-2024: {np.corrcoef(hom, dis)[0, 1]:.3f} "
              f"(p = {pearsonr(hom, dis)[1]:.3f}, n = 10)",
              f"- Spearman rho 2015-2024: {spearmanr(hom, dis)[0]:.3f}",
              f"- Pearson r of first differences: {np.corrcoef(np.diff(hom), np.diff(dis))[0, 1]:.3f}",
              f"- Levels incl. provisional 2025: "
              f"{np.corrcoef(h.loc[2015:2025].homicide_victims_annualised, h.loc[2015:2025].disappearances_recorded)[0, 1]:.3f}",
              "", "| year | homicides | found dead | still missing | hom + dead | hom + missing |",
              "|---|---:|---:|---:|---:|---:|"]
    for yr in (2019, 2024):
        hv = int(h.loc[yr, "homicide_victims"])
        dd = int(fy.loc[str(yr), "loc_sin_vida"])
        mm = int(fy.loc[str(yr), "desap_y_nollocal"])
        lines.append(f"| {yr} | {hv:,} | {dd:,} | {mm:,} | {hv + dd:,} | {hv + mm:,} |")
    lines += ["", "Reading: the substitution hypothesis predicts a flat homicides + still-missing "
              "total, and that total is nearly flat (-1.5%). The article's earlier test used "
              "homicides + found dead, which the hypothesis does not predict to be flat.", ""]

    # 3/4 mirror
    if not MIRROR.exists():
        lines += ["## 3-4. BLOCKED: record-level mirror not present", ""]
    else:
        m = pd.read_csv(MIRROR, dtype=str)
        conf = m.ESTATUS_VICTIMA.eq("CONFIDENCIAL")
        c = m[conf]
        lines += ["## 3. What a CONFIDENCIAL row carries", "",
                  f"{conf.sum():,} of {len(m):,} rows ({conf.mean():.4%}).", "",
                  "| field | distinct values among confidential rows | example |", "|---|---:|---|"]
        for col in m.columns:
            vals = c[col].dropna().unique()
            ex = "CONFIDENCIAL" if (len(vals) == 1 and vals[0] == "CONFIDENCIAL") else str(vals[0])[:40]
            lines.append(f"| {col} | {len(vals):,} | {ex} |")
        # Same grouping as article fig K (src/filing_authority.py): state offices are
        # kept apart from the national commission and federal prosecutors.
        sys.path.insert(0, str(ROOT / "src"))
        from filing_authority import authority
        kind = m.ORIGEN_REPORTE.map(authority).replace(
            {"state_prosecutor": "prosecutor", "state_commission": "search commission"})
        m = m.assign(conf=conf, kind=kind)
        nat = m.groupby("kind").conf.agg(["size", "mean"])
        lines += ["", "## 4. Confidential share by filing authority (article §6, fig K)", "",
                  "| filing authority | records | confidential share |", "|---|---:|---:|"]
        for kk, r in nat.sort_values("size", ascending=False).iterrows():
            lines.append(f"| {kk} | {int(r['size']):,} | {r['mean']:.1%} |")
        g = m[m.CVE_ENT != "99"].groupby(["ENTIDAD", "kind"]).conf.agg(["size", "mean"]).reset_index()
        lines += ["", "Spread across states (cells with at least 100 records):", ""]
        for kk in ["portal", "prosecutor", "search commission"]:
            s = g[(g.kind == kk) & (g["size"] >= 100)]["mean"]
            lines.append(f"- {kk}: {len(s)} states, range {s.min():.1%}-{s.max():.1%}, "
                         f"interquartile {s.quantile(.25):.1%}-{s.quantile(.75):.1%}")
        w = g.pivot(index="ENTIDAD", columns="kind", values="mean")
        n = g.pivot(index="ENTIDAD", columns="kind", values="size")
        big = (n["prosecutor"] >= 300) & (n["search commission"] >= 300)
        lines += ["", "States with at least 300 records from both prosecutors and the search commission:", "",
                  "| state | prosecutor | search commission | portal |", "|---|---:|---:|---:|"]
        for st, r in w[big].iterrows():
            lines.append(f"| {st.title()} | {r['prosecutor']:.0%} | {r['search commission']:.0%} | "
                         f"{r['portal']:.0%} |")
        lines += ["", "Reading: family reports filed directly through the CNB portal are confidential "
                  "at a similar rate in almost every state, while the share among records filed by "
                  "state prosecutors and commissions ranges from about 3% to about 96%. Case mix "
                  "differs by channel, so this is descriptive, not causal.", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
